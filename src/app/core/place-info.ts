const labelOf = (line: string) => (line.includes('：') ? line.split('：')[0] + '：' : '');

/** 把幾行依標籤合併進備註：同標籤的舊行會被新行取代（資料更新時不會一直長出重複行） */
export function mergeNote(note: string, lines: string[]): string {
  let cur = (note || '').split('\n').map((x) => x.trim()).filter(Boolean);
  for (const line of lines) {
    const label = labelOf(line);
    if (label) cur = cur.filter((l) => !l.startsWith(label));
    cur.push(line);
  }
  return cur.join('\n');
}

interface Applicable { title: string; hours: string; note: string; subs: Sub[] }

/** 依站名找到地點資料並套用；沒有對應資料的站原封不動回傳 */
export function applyInfo<T extends Applicable>(item: T): T {
  const info = PLACE_INFO.find((p) => p.match.test(item.title));
  if (!info) return item;
  const out: T = { ...item, subs: item.subs.map((s) => ({ ...s })) };
  if (info.hours !== undefined) out.hours = info.hours;
  if (info.note) out.note = info.note.join('\n');
  else if (info.append) out.note = mergeNote(out.note, info.append);
  for (const rule of info.subs ?? []) {
    out.subs.forEach((s) => {
      if (rule.match.test(s.name)) {
        if (rule.hours !== undefined) s.hours = rule.hours;
        if (rule.note !== undefined) s.note = rule.note;
      }
    });
  }
  if (info.patch) Object.assign(out, info.patch);
  return out;
}
